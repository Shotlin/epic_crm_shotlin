    story += [parties, Spacer(1, 5 * mm)]

    facts = Table([
        [Paragraph("VALID UNTIL", label), Paragraph("PLACE OF SUPPLY", label), Paragraph("RECIPIENT", label), Paragraph("CURRENCY", label)],
        [Paragraph("31 August 2026", body), Paragraph("Maharashtra / 27", body), Paragraph("GST registered", body), Paragraph("INR", body)],
    ], colWidths=[43.5 * mm] * 4)
    facts.setStyle(TableStyle([("BOX", (0, 0), (-1, -1), .6, LINE), ("INNERGRID", (0, 0), (-1, -1), .6, LINE), ("BACKGROUND", (0, 0), (-1, -1), PALE), ("LEFTPADDING", (0, 0), (-1, -1), 8), ("TOPPADDING", (0, 0), (-1, -1), 6), ("BOTTOMPADDING", (0, 0), (-1, -1), 7)]))
    story += [facts, Spacer(1, 7 * mm)]

    rows = [["#", "PRODUCT / CLASSIFICATION", "GST", "DISCOUNT", "TAXABLE"]]
