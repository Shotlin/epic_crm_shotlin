ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "output" / "pdf" / "epic-bos-india-quotation.pdf"

INK = colors.HexColor("#102B2C")
COPPER = colors.HexColor("#D9672B")
GOLD = colors.HexColor("#F0B84B")
